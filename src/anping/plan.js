// 熱蘭遮城與大員市鎮平面：描自成大博物館〈熱蘭遮城與大員城下町〉今昔疊圖（使用者素材 熱蘭遮/018c38e5….jpg，
// 以 1600 px 寬檢視座標記錄）。比例尺 300 ft = 172 px（0.532 m/px）；以內城中心對位到 OSM 安平古堡平臺，
// 再以現存「熱蘭遮城殘跡」（外堡南牆，OSM）校正：疊圖本身朝正北、旋轉 0°，整體平移東 3 m、北 8 m 後，
// 南牆位置相差 < 3 m、方向相差 2°（docs/anping-evidence.md）。
// 場景座標：公尺，x 向東、z 向南、y 向上；原點＝OSM 安平古堡平臺中心（23.0015° N, 120.16085° E）；內城中心在 (3, -8)。
const S = 0.532, ROT = 0, C0 = [629.2, 270], SHIFT = [3, -8];
export function fromPlan([px, py]) {
  const e = (px - C0[0]) * S, n = -(py - C0[1]) * S;
  const E = e * Math.cos(ROT) - n * Math.sin(ROT), N = e * Math.sin(ROT) + n * Math.cos(ROT);
  return [E + SHIFT[0], -N + SHIFT[1]];
}
// 疊圖中城堡區放大圖（2.4 倍，左上角 = 檢視座標 280,80）
const fromCrop = ([x, y]) => fromPlan([280 + x / 2.4, 80 + y / 2.4]);

